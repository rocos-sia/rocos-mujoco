#!/usr/bin/env python3
"""Derive an opt-in shoulder-origin model without changing physical geometry."""
from pathlib import Path
import argparse
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1] / 'config/dualarm'


def generated_models():
    urdf = ET.parse(ROOT / 'urdf/dualarm.urdf').getroot()
    mjcf = ET.parse(ROOT / 'mjcf/dualarm.xml').getroot()
    urdf.set('name', 'dualarm_shoulder_v1')
    mjcf.set('model', 'dualarm_shoulder_v1')
    pedestal = mjcf.find("worldbody/body[@name='base_link']")
    frames = {'schema_version': 1, 'profile': 'shoulder-v1', 'parent': 'base_link', 'arms': {}}
    for side in ('Left', 'Right'):
        base = side.lower() + '_base'
        joint = urdf.find(f"joint[@name='{side}_Joint1']")
        offset = joint.find('origin').get('xyz')
        frames['arms'][side.lower()] = {'base_link': base, 'tip_link': side + '_Link7',
            'translation': [float(v) for v in offset.split()], 'rpy': [0, 0, 0]}
        # Translate only. Preserve the existing J1 rotation and axis, and gravity.
        urdf.append(ET.Element('link', name=base))
        mount = ET.SubElement(urdf, 'joint', name=base + '_mount', type='fixed')
        ET.SubElement(mount, 'parent', link='base_link')
        ET.SubElement(mount, 'child', link=base)
        ET.SubElement(mount, 'origin', xyz=offset, rpy='0 0 0')
        joint.find('parent').set('link', base)
        joint.find('origin').set('xyz', '0 0 0')
        body = pedestal.find(f"body[@name='{side}_Link1']")
        wrapper = ET.Element('body', name=base, pos=offset)
        pedestal.insert(list(pedestal).index(body), wrapper)
        pedestal.remove(body)
        wrapper.append(body)
        body.set('pos', '0 0 0')
    yield ROOT / 'shoulder_frames.json', json.dumps(frames, indent=2) + '\n'
    scene = ET.parse(ROOT / 'mjcf/scene.xml').getroot()
    scene.set('model', 'dualarm shoulder scene')
    scene.find('include').set('file', 'dualarm_shoulder.xml')
    for relative, tree in [('urdf/dualarm_shoulder.urdf', urdf),
                           ('mjcf/dualarm_shoulder.xml', mjcf),
                           ('mjcf/scene_shoulder.xml', scene)]:
        tree.insert(0, ET.Comment(' Generated by scripts/generate_dualarm_shoulders.py; original geometry/axes preserved. '))
        ET.indent(tree, space='  ')
        yield ROOT / relative, ET.tostring(tree, encoding='unicode') + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in generated_models():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Stale generated model: {path}')
        else:
            path.write_text(content)
        print(('Checked ' if args.check else 'Generated ') + str(path))


if __name__ == '__main__':
    main()
